--   ۲) RLS فعال است با policy tenant_isolation + FORCE.
--   ۳) GRANT SELECT, INSERT به clinical_app و platform_app — بدونِ UPDATE/DELETE.
--   ۴) ایندکس‌های idx_sug_events_rule_stats و idx_sug_events_patient وجود دارند.
--   ۵) idempotency: اجرای مجدد بدونِ خطا.
