-- ---------------------------------------------------------------------------
-- invoice_item_payments — وضعیتِ پرداختِ هر آیتمِ فاکتور. FK invoice_id → invoices.
--   surrogate id (BIGINT IDENTITY PK — Django ORM با PKِ مرکب ناسازگار است)؛ کلیدِ طبیعیِ
--   منبع (tenant_id, invoice_id, item_type, item_id) اکنون به‌صورتِ CONSTRAINT UNIQUE حفظ
--   می‌شود. is_paid → BOOLEAN. item_type با CHECK یکپارچه‌شده (هر چهار مقدار).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounting.invoice_item_payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
    invoice_id    BIGINT NOT NULL REFERENCES accounting.invoices(id),
    item_type     TEXT NOT NULL CHECK (item_type IN ('visit','injection','procedure','consumable')),
    item_id       BIGINT NOT NULL,
    payment_type  TEXT,                                    -- cash|card|insurance
    is_paid       BOOLEAN NOT NULL DEFAULT FALSE,          -- بولی
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_invoice_item_payments UNIQUE (tenant_id, invoice_id, item_type, item_id)
);

-- ---------------------------------------------------------------------------
-- payroll_settings — تنظیماتِ حقوقِ کادر درمان. FK staff_id → medical_staff (یکتا per-tenant).
--   ⚠️ مهاجرتِ literal: هر ۹ ستونِ نام‌دار عیناً نگه داشته می‌شوند —
--      پولی (base_morning/base_evening/base_night/visit_fee) → NUMERIC(14,0)؛
--      درصدی (injection/procedure/tax/nursing/nurse_procedure_percent) → NUMERIC(6,3).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounting.payroll_settings (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
    staff_id                 BIGINT NOT NULL REFERENCES accounting.medical_staff(id),
    base_morning             NUMERIC(14,0) NOT NULL DEFAULT 0,  -- پول → تومان
    base_evening             NUMERIC(14,0) NOT NULL DEFAULT 0,  -- پول → تومان
    base_night               NUMERIC(14,0) NOT NULL DEFAULT 0,  -- پول → تومان
    visit_fee                NUMERIC(14,0) NOT NULL DEFAULT 0,  -- پول → تومان
    injection_percent        NUMERIC(6,3) NOT NULL DEFAULT 0 CHECK (injection_percent BETWEEN 0 AND 100),   -- درصد (نه تومان)
    procedure_percent        NUMERIC(6,3) NOT NULL DEFAULT 0 CHECK (procedure_percent BETWEEN 0 AND 100),   -- درصد
    tax_percent              NUMERIC(6,3) NOT NULL DEFAULT 0 CHECK (tax_percent BETWEEN 0 AND 100),   -- درصد
    nursing_percent          NUMERIC(6,3) NOT NULL DEFAULT 0 CHECK (nursing_percent BETWEEN 0 AND 100),   -- درصد
    nurse_procedure_percent  NUMERIC(6,3) NOT NULL DEFAULT 0 CHECK (nurse_procedure_percent BETWEEN 0 AND 100),   -- درصد
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_payroll_settings_tenant_staff UNIQUE (tenant_id, staff_id)
);

-- ---------------------------------------------------------------------------
-- activity_logs — لاگِ فعالیتِ کاربران. user_id → platform.users (cross-schema به platform مجاز)،
--   invoice_id → invoices، patient_id → patients. amount → NUMERIC(14,0). created_at لحظه → TIMESTAMPTZ.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounting.activity_logs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
    user_id          BIGINT REFERENCES platform.users(id),  -- cross-schema به platform (مجاز)
    username         TEXT,
    action_type      TEXT NOT NULL,
    action_category  TEXT NOT NULL,
    description      TEXT,
    target_type      TEXT,
    target_id        BIGINT,
    target_name      TEXT,
    invoice_id       BIGINT REFERENCES accounting.invoices(id),
    patient_id       BIGINT REFERENCES accounting.patients(id),
    patient_name     TEXT,
    amount           NUMERIC(14,0) NOT NULL DEFAULT 0,      -- پول → تومان
    old_value        TEXT,
    new_value        TEXT,
    ip_address       TEXT,
    user_agent       TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- user_active_shift — شیفتِ فعالِ کاربر (تغییرِ دستیِ مستقل از ساعت).
--   ⚠️ منبع PKِ user_id دارد؛ اینجا برای tenant_id به (id IDENTITY PK + UNIQUE(tenant_id,
--      user_id)) بازنویسی شد. user_id → platform.users. active_shift TEXT NOT NULL.
--      work_date تقویمی → DATE. shift_started_at لحظه → TIMESTAMPTZ.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounting.user_active_shift (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
