-- ###########################################################################
-- ۱) UNIQUE(tenant_id, id) روی clinical.prescriptions
--    پیش‌نیازِ FKِ مرکبِ prescription_items → prescriptions (Batch 4b §۴)
-- ###########################################################################
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'clinical.prescriptions'::regclass
          AND conname   = 'uq_prescriptions_tenant_id'
    ) THEN
        ALTER TABLE clinical.prescriptions
            ADD CONSTRAINT uq_prescriptions_tenant_id
            UNIQUE (tenant_id, id);
    END IF;
END$$;

-- ###########################################################################
-- ۲) clinical.encounters — جدولِ جدیدِ ویزیت/ارتباطِ بالینی
-- ###########################################################################
CREATE TABLE IF NOT EXISTS clinical.encounters (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id               BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
    -- FK مرکب composite → cross-tenant reference ساختاراً غیرممکن
    patient_link_id         BIGINT NOT NULL,
    -- doctor_id: cross-schema FKِ مجاز (clinical → accounting)
    doctor_id               BIGINT,                              -- nullable؛ ON DELETE SET NULL
    encounter_type          TEXT NOT NULL DEFAULT 'visit'
                            CHECK (encounter_type IN ('visit','follow_up','phone','remote')),
    encounter_at            TIMESTAMPTZ NOT NULL,
    chief_complaint         TEXT,
    status                  TEXT NOT NULL DEFAULT 'open'
                            CHECK (status IN ('open','completed','cancelled')),
    completed_at            TIMESTAMPTZ,                         -- nullable، بدونِ DEFAULT
    summary_note            TEXT,
    -- appointment_id: FKِ مرکب به appointments (nullable)
    appointment_id          BIGINT,                              -- ON DELETE SET NULL
    -- accounting_invoice_id: cross-schema FKِ مجاز (clinical → accounting) DEFERRABLE
    accounting_invoice_id   BIGINT,                              -- nullable snapshot؛ DEFERRABLE
    created_by              TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Tenant-safety: UNIQUE(tenant_id, id) برای هدفِ FKِ مرکبِ childها
    CONSTRAINT uq_encounters_tenant_id UNIQUE (tenant_id, id),

    -- FK مرکب به patient_links (cross-tenant rejection)
    CONSTRAINT fk_encounters_patient FOREIGN KEY (tenant_id, patient_link_id)
        REFERENCES clinical.patient_links (tenant_id, id),

    -- FK مرکب به appointments (اختیاری؛ SET NULL هنگامِ حذفِ نوبت)
    -- appointments.uq_appointments_tenant_id موجود است (slice2b) ✓
    CONSTRAINT fk_encounters_appointment FOREIGN KEY (tenant_id, appointment_id)
        REFERENCES clinical.appointments (tenant_id, id)
        ON DELETE SET NULL,

    -- FK مرکب cross-schema: doctor_id → accounting.medical_staff (جهتِ مجاز)
    -- accounting.medical_staff.uq_medical_staff_tenant_id موجود است (slice3) ✓
    CONSTRAINT fk_encounters_doctor FOREIGN KEY (tenant_id, doctor_id)
        REFERENCES accounting.medical_staff (tenant_id, id)
        ON DELETE SET NULL,

    -- FK مرکب cross-schema: accounting_invoice_id → accounting.invoices (جهتِ مجاز)
    -- DEFERRABLE INITIALLY DEFERRED: همانِ الگوی slice4 (ETL می‌تواند ردیفِ بالینی را
    -- پیش از ردیفِ accounting در همان تراکنش درج کند؛ بررسی فقط در commit)
    -- accounting.invoices.uq_invoices_tenant_id موجود است (slice3) ✓
    CONSTRAINT fk_encounters_invoice FOREIGN KEY (tenant_id, accounting_invoice_id)
        REFERENCES accounting.invoices (tenant_id, id)
        ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED
);

-- Index: جستجوی پروندهٔ بیمار به ترتیبِ نزولِ زمان (شایع‌ترین query)
CREATE INDEX IF NOT EXISTS idx_encounters_patient_at
    ON clinical.encounters (patient_link_id, encounter_at DESC);

-- Index: صفِ وضعیت + زمان (برای worklist و Control Room)
CREATE INDEX IF NOT EXISTS idx_encounters_tenant_status_at
    ON clinical.encounters (tenant_id, status, encounter_at DESC);

-- updated_at auto-trigger (تابعِ clinical.set_updated_at() از slice4a)
DROP TRIGGER IF EXISTS trg_encounters_updated_at ON clinical.encounters;
CREATE TRIGGER trg_encounters_updated_at
    BEFORE UPDATE ON clinical.encounters
    FOR EACH ROW EXECUTE FUNCTION clinical.set_updated_at();

