--   ۴) clinical.prescription_items — جدولِ جدیدِ اقلامِ نسخه
--      * UNIQUE(tenant_id, id) روی clinical.prescriptions (پیش‌نیازِ FKِ مرکب)
--      * drug_class FKِ soft (nullable + ON DELETE SET NULL) — دلیل: drug_catalog seedها
--        پیش از این slice از Python bootstrap وارد می‌شوند؛ FK واقعی ریسک orphan دارد.
--
--   ۵) doctor_id + chief_complaint به clinical.appointments
--      * FKِ مرکب cross-schema (tenant_id, doctor_id) → accounting.medical_staff(tenant_id, id)
--        ON DELETE SET NULL (جهتِ مجازِ clinical→accounting)
--
-- idempotency:
--   * CREATE TABLE IF NOT EXISTS
--   * ALTER TABLE … ADD COLUMN IF NOT EXISTS   (Pg13+)
