-- ۳e: clinical.doctor_visit_log ← encounter_id (soft — بدونِ FK واقعی)
--
--   ⚠️ soft رها شد: doctor_visit_log یک لجرِ مرزیِ accounting-snapshot است. این جدول
--   از accounting.invoices ساخته می‌شود (FK DEFERRABLE در slice4). اضافه‌کردنِ FK واقعی
--   از doctor_visit_log → encounters ریسکِ circular-dependency در ETL دارد
--   (هر encounters ممکن است از doctor_visit_log ساخته شود و بالعکس). همچنین
--   doctor_visit_log.tenant_id همیشه NOT NULL است اما encounters ممکن است بعد از
--   doctor_visit_log ساخته شود؛ DEFERRABLE روی این FK هم ریسکِ deadlock ایجاد می‌کند.
--   → encounter_id در doctor_visit_log به‌عنوانِ soft reference (nullable BIGINT بدونِ FK)
--   اضافه می‌شود. ORM/service-layer مسئولِ ثبتِ صحیحِ آن است.
--   نیازمندِ تأییدِ معمارِ داده قبل از تبدیل به FK واقعی.
-- ---------------------------------------------------------------------------
ALTER TABLE clinical.doctor_visit_log
    ADD COLUMN IF NOT EXISTS encounter_id BIGINT;                -- soft ref، بدونِ FK

-- ###########################################################################
-- ۴) ستون‌های structured dose به clinical.patient_medications
--    همه nullable (additive؛ ردیف‌های قدیمی NULL می‌مانند)
-- ###########################################################################

ALTER TABLE clinical.patient_medications
    ADD COLUMN IF NOT EXISTS dose_value  NUMERIC(10,3);          -- مقدارِ عددیِ دوز

ALTER TABLE clinical.patient_medications
    ADD COLUMN IF NOT EXISTS dose_unit   TEXT;                   -- 'mg','mcg','IU','unit',…

ALTER TABLE clinical.patient_medications
    ADD COLUMN IF NOT EXISTS frequency   TEXT;                   -- CHECK پایین (DO $$)

ALTER TABLE clinical.patient_medications
    ADD COLUMN IF NOT EXISTS route       TEXT;                   -- CHECK پایین (DO $$)

-- frequency CHECK (nullable → IS NULL OR IN (...))
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'clinical.patient_medications'::regclass
          AND conname   = 'chk_medications_frequency'
    ) THEN
        ALTER TABLE clinical.patient_medications
            ADD CONSTRAINT chk_medications_frequency
            CHECK (frequency IS NULL OR frequency IN (
                'od','bid','tid','qid','qod','weekly','monthly','prn',
                'with_meal','bedtime','other'
            ));
    END IF;
END$$;

-- route CHECK (nullable → IS NULL OR IN (...))
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'clinical.patient_medications'::regclass
          AND conname   = 'chk_medications_route'
    ) THEN
        ALTER TABLE clinical.patient_medications
            ADD CONSTRAINT chk_medications_route
            CHECK (route IS NULL OR route IN (
                'oral','sublingual','sc','im','iv','topical','inhaled','other'
            ));
    END IF;
END$$;

-- ###########################################################################
-- ۵) clinical.prescription_items — اقلامِ ساختاریافتهٔ نسخه
--    prescriptions.items JSONB (raw payload) دست‌نخورده می‌ماند.
--    این جدول structured‌ترِ همان payload است.
-- ###########################################################################
CREATE TABLE IF NOT EXISTS clinical.prescription_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT NOT NULL DEFAULT 1 REFERENCES platform.tenants(id),
    -- FK مرکب → prescriptions (tenant-safe؛ uq_prescriptions_tenant_id ساخته شد بالا)
    prescription_id  BIGINT NOT NULL,
    drug_name        TEXT NOT NULL,
    -- drug_class: FKِ soft (nullable + ON DELETE SET NULL)
    --   ⚠️ soft رها شد: drug_catalog seedها از Python bootstrap وارد می‌شوند (نه inline SQL).
    --   drug_classes.class_key در slice2 seed شده؛ اما prescription_items.drug_class
    --   ممکن است مقادیرِ free-text داشته باشد که در drug_classes نیستند (کلاسِ جدید،
    --   دارویِ ترکیبی، یا کلاسِ خارج از seed). FK واقعی باعثِ FK violation در این موارد
    --   می‌شود و ریسکِ orphan دارد. → soft soft-reference: nullable TEXT.
    --   نیازمندِ تأییدِ معمارِ داده قبل از تبدیل به FK واقعی.
    drug_class       TEXT,                                       -- soft ref به drug_classes.class_key
    dose_value       NUMERIC(10,3),
    dose_unit        TEXT,
    frequency        TEXT
                     CHECK (frequency IS NULL OR frequency IN (
                         'od','bid','tid','qid','qod','weekly','monthly','prn',
                         'with_meal','bedtime','other'
                     )),
    route            TEXT
                     CHECK (route IS NULL OR route IN (
                         'oral','sublingual','sc','im','iv','topical','inhaled','other'
                     )),
    quantity         INTEGER CHECK (quantity IS NULL OR quantity > 0),
    duration_days    INTEGER CHECK (duration_days IS NULL OR duration_days > 0),
    instructions     TEXT,

    -- FK مرکب به prescriptions (tenant-safe)
    CONSTRAINT fk_prescription_items_prescription FOREIGN KEY (tenant_id, prescription_id)
        REFERENCES clinical.prescriptions (tenant_id, id)
        ON DELETE CASCADE                                        -- حذفِ نسخه → حذفِ اقلامش
);

CREATE INDEX IF NOT EXISTS idx_prescription_items_prescription
    ON clinical.prescription_items (prescription_id);

